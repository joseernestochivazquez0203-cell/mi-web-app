def ejecutar_simulacion(precio_futuro_inicial, margen_llamada, alpha_seleccionado, num_simulaciones):
    """
    Ejecuta la simulación de Monte Carlo mediante el Método de Fisher,
    genera las tablas estadísticas, de riesgo (VaR) y despliega los 4 histogramas dinámicos.
    """
    # 1. Parámetros del método de Fisher y del contrato
    B4_drift = 17.6   # Promedio / Drift
    B5_desv = 24.69   # Desviación estándar anual (%)
    B10 = 0.018        # Cetes
    B11 = 0.01612      # T-Bills

    tamano_contrato = 10000  # Tamaño del contrato
    capital_inicial = 15000  # Inversión inicial fija en 15,000

    # 2. Definir el rango de fechas
    fechas = pd.date_range(start='2026-10-15', end='2026-12-17', freq='D')
    n = len(fechas)

    sigma = B5_desv / 100.0
    dt = 1 / 252.0

    resultados_simulaciones = []

    # 3. Bucle de Monte Carlo para cada simulación
    for sim in range(num_simulaciones):
        # Generar variables aleatorias normales estándar
        Z = np.random.standard_normal(n)

        precios = np.zeros(n)
        precios[0] = 18.44  # Día 1 base

        # Aplicar la fórmula de Fisher (Movimiento Geométrico Browniano)
        for i in range(1, n):
            factor_exponente = (B10 - B11 - 0.5 * (sigma ** 2)) * dt + (sigma / np.sqrt(252)) * Z[i]
            precios[i] = precios[i - 1] * np.exp(factor_exponente)

        # Calcular variación diaria
        variacion_diaria = pd.Series(precios).pct_change()
        variacion_diaria.iloc[0] = 0.0

