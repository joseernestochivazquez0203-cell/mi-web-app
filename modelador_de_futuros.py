        # Comisiones ($50 al inicio y $50 al final)
        comisiones = np.zeros(n)
        comisiones[0] = 50.0
        comisiones[-1] = 50.0
        total_comisiones = np.sum(comisiones)

        # Simulación día a día para Margen y Depósitos por llamadas
        margen = np.zeros(n)
        depositos_llamadas = np.zeros(n)
