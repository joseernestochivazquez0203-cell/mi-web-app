import numpy as np
import pandas as pd
from scipy import stats
import matplotlib.pyplot as plt
import ipywidgets as widgets
from IPython.display import display, clear_output

def ejecutar_simulacion(precio_futuro_inicial, margen_llamada, alpha_seleccionado, num_simulaciones):
    """
    Ejecuta la simulación de Monte Carlo y actualiza los 4 histogramas independientes
    conforme se modifican los valores de los deslizadores (futuro, margen, alpha).
    """
    # 1. Parámetros generales
    B3 = 28.52977  # Parámetro de forma (shape)
    B4 = 18.32123  # Parámetro de escala (scale)
    tamano_contrato = 10000  # Tamaño del contrato
    capital_inicial = 15000.0

    # 2. Definir el rango de fechas
    fechas = pd.date_range(start='2026-10-15', end='2026-12-17', freq='D')
    n = len(fechas)

    resultados_simulaciones = []

    # 3. Bucle de Monte Carlo para cada simulación
    for sim in range(num_simulaciones):
        # Generar números aleatorios uniformes
        U = np.random.uniform(0.0001, 0.9999, n)

        # Precios log-logísticos base y precio fijo del día 1 en 18.44
        precios = B4 * (U / (1 - U)) ** (1 / B3)
        precios[0] = 18.44

        # Calcular variación diaria
        variacion_diaria = pd.Series(precios).pct_change()
        variacion_diaria.iloc[0] = 0.0

        # Precio Futuro (comienza en el valor deslizado y se encadena con la variación diaria)
        precio_futuro = np.zeros(n)
        precio_futuro[0] = precio_futuro_inicial
        for i in range(1, n):
            precio_futuro[i] = precio_futuro[i - 1] * (1 + variacion_diaria.iloc[i])

        # Valuación y ganancia/pérdida diaria basada en el precio futuro y tamaño de contrato
        valuacion_contrato = precio_futuro * tamano_contrato
        gp_diaria = np.diff(valuacion_contrato, prepend=valuacion_contrato[0])
        gp_diaria[0] = 0.0

        # Comisiones ($50 inicio y $50 fin)
        comisiones = np.zeros(n)
        comisiones[0] = 50.0
        comisiones[-1] = 50.0
        total_comisiones = np.sum(comisiones)

        # Simulación día a día
        margen = np.zeros(n)
        depositos_llamadas = np.zeros(n)
        capital_neto_inicial = capital_inicial - comisiones[0]

        for i in range(n):
            margen_prev = capital_neto_inicial if i == 0 else margen[i - 1]
            gp = gp_diaria[i]
            com = comisiones[i] if i == n - 1 else 0.0

            m_temp = margen_prev + gp - com

            dep = 0.0
            if m_temp < margen_llamada:
                dep = 15000.0 - m_temp
                m_temp = 15000.0

            margen[i] = m_temp
            depositos_llamadas[i] = dep

        # Extracción de métricas para la simulación actual
        precio_final = precio_futuro[-1]
        ganancia_bruta_mercado = (precio_final - precio_futuro_inicial) * tamano_contrato
        total_depositos_llamadas = np.sum(depositos_llamadas)
        total_capital_inyectado = capital_inicial + total_depositos_llamadas
        efectivo_retirable = margen[-1]

        # Llamada máxima y datos asociados
        max_deposito = np.max(depositos_llamadas)
        if max_deposito > 0:
            idx_max = np.argmax(depositos_llamadas)
            dia_llamada_max = fechas[idx_max].strftime('%d/%m/%Y')
            precio_dolar_llamada_max = precio_futuro[idx_max]
        else:
            dia_llamada_max = "Sin llamadas"
            precio_dolar_llamada_max = 0.0

        resultados_simulaciones.append({
            'Simulación (#)': sim + 1,
            'Inversión inicial': capital_inicial,
            'Ganancia bruta del mercado': ganancia_bruta_mercado,
            'Depósitos por llamadas': total_depositos_llamadas,
            'Total de capital inyectado': total_capital_inyectado,
            'Comisiones totales': total_comisiones,
            'Efectivo total retirable': efectivo_retirable,
            'Llamada máxima': max_deposito,
            'Día de llamada máxima': dia_llamada_max,
            'Precio dólar (llamada máx.)': precio_dolar_llamada_max,
            'Precio dólar (final)': precio_final,
        })

    df_excel = pd.DataFrame(resultados_simulaciones)

    # 4. Crear la tabla de estadísticos
    columnas_numericas = [
        'Ganancia bruta del mercado',
        'Depósitos por llamadas',
        'Total de capital inyectado',
        'Efectivo total retirable',
        'Llamada máxima',
        'Precio dólar (llamada máx.)',
        'Precio dólar (final)',
    ]

    dic_estadisticos = []
    for col in columnas_numericas:
        serie = df_excel[col]
        moda_res = stats.mode(np.round(serie, 2), keepdims=True)
        moda_val = moda_res.mode[0] if len(moda_res.mode) > 0 else 0.0

        dic_estadisticos.append({
            'Métrica': col,
            'Mínimo': serie.min(),
            'Q1 (25%)': serie.quantile(0.25),
            'Mediana (50%)': serie.median(),
            'Promedio': serie.mean(),
            'Q3 (75%)': serie.quantile(0.75),
            'Máximo': serie.max(),
            'Moda': moda_val,
            'Desviación Estándar': serie.std(),
        })

    df_estadisticos = pd.DataFrame(dic_estadisticos)

    # 5. Cálculo de Cutoff y VaR con base en 190,000 y el Alpha seleccionado
    valor_inicial = 190000.0
    df_excel['Valor Total Final'] = valor_inicial + df_excel['Ganancia bruta del mercado']

    p = alpha_seleccionado
    etiqueta = f'{int(p*100)}%'
    serie_valor = df_excel['Valor Total Final']

    val_cutoff = serie_valor.quantile(p)
    val_var = valor_inicial - val_cutoff

    df_cut_var_valor = pd.DataFrame([{
        'Métrica': 'Valor Total del Contrato',
        'Tipo Cutoff': val_cutoff,
        'Tipo VaR': val_var,
        'Nivel Alpha (%)': etiqueta
    }])

    # Limpiar salida anterior y actualizar en vivo
    clear_output(wait=True)

    print("--- VISTA PREVIA DE LA TABLA DE SIMULACIONES (Primeras 10) ---")
    display(df_excel.head(10))

    print("\n--- TABLA APARTE DE ESTADÍSTICOS ---")
    display(df_estadisticos)

    print(f"\n--- TABLA DE CUTOFF Y VaR PARA ALPHA = {etiqueta} (Base: 190,000) ---")
    display(df_cut_var_valor)

    # 6. Generar los 4 histogramas dinámicos vinculados a los deslizadores
    plt.figure(figsize=(10, 6))

    plt.subplot(2, 2, 1)
    plt.hist(df_excel['Efectivo total retirable'], bins=50, color='dodgerblue', edgecolor='black', alpha=0.7)
    plt.title(f'Efectivo Total Retirable (Margen Llamada: ${margen_llamada:,.0f})')
    plt.xlabel('Monto ($)')
    plt.ylabel('Frecuencia')
    plt.grid(True, linestyle='--', alpha=0.5)

    plt.subplot(2, 2, 2)
    plt.hist(df_excel['Ganancia bruta del mercado'], bins=50, color='forestgreen', edgecolor='black', alpha=0.7)
    plt.title(f'Ganancia Bruta (Futuro Inicial: {precio_futuro_inicial})')
    plt.xlabel('Monto ($)')
    plt.ylabel('Frecuencia')
    plt.grid(True, linestyle='--', alpha=0.5)

    plt.subplot(2, 2, 3)
    plt.hist(df_excel['Total de capital inyectado'], bins=50, color='darkorange', edgecolor='black', alpha=0.7)
    plt.title('Capital Inyectado Total')
    plt.xlabel('Monto ($)')
    plt.ylabel('Frecuencia')
    plt.grid(True, linestyle='--', alpha=0.5)

    plt.subplot(2, 2, 4)
    plt.hist(df_excel['Llamada máxima'], bins=50, color='crimson', edgecolor='black', alpha=0.7)
    plt.title(f'Llamada Máxima ')
    plt.xlabel('Monto ($)')
    plt.ylabel('Frecuencia')
    plt.grid(True, linestyle='--', alpha=0.5)

    plt.tight_layout()
    plt.show()

